import {fileURLToPath} from 'node:url';
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { getRobustnessView } from './demo-model.mjs';
import { validateResultView } from './result-view-model.mjs';
const root=path.dirname(fileURLToPath(import.meta.url));
const base=path.join(root,'fixtures')+path.sep;
const files={};
for(const n of ['input','report','manifest'])files[n]=await fs.readFile(base+'baseline/'+n+'.json');
const manifest=JSON.parse(files.manifest);
for(const n of ['input','report'])assert.equal(crypto.createHash('sha256').update(files[n]).digest('hex'),manifest[n+'Sha256']);
const data={input:JSON.parse(files.input),report:JSON.parse(files.report),provenance:{inputSha256:manifest.inputSha256,reportSha256:manifest.reportSha256},readiness:JSON.parse(await fs.readFile(base+'readiness.json'))};
const robustBase=base+'robustness/';
const robustManifest=JSON.parse(await fs.readFile(robustBase+'manifest.json'));
for(const n of ['input','report','plan']){
  const bytes=await fs.readFile(robustBase+n+'.json');
  assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'),robustManifest[n+'Sha256']);
  if(n==='input') assert.deepEqual(JSON.parse(bytes),data.input);
  if(n==='report') data.robustness=JSON.parse(bytes);
  if(n==='plan') assert.deepEqual(JSON.parse(bytes),data.robustness.plan);
}
data.provenance.robustnessReportSha256=robustManifest.reportSha256;
data.provenance.robustnessPlanSha256=robustManifest.planSha256;
for(const seed of data.robustness.plan.seeds)for(const weight of data.robustness.plan.fairnessWeights)
  for(const scope of ['ALL',...Object.keys(data.report.variants[0].strata)])getRobustnessView(data,{seed,weight,scope});
assert.equal(data.report.datasetKind,'SYNTHETIC_TEST_ONLY');
assert.equal(data.readiness.experimentAuthorized,false);
const context={};for(const k of ['datasetId','datasetKind','coordinateSystem','seed','fairnessWeight','longTailPlaceIds'])context[k]=data.input[k];
context.nodes=data.input.nodes.map(n=>Object.fromEntries(['id','name','category','ticketPrice','suggestedMinutes'].map(k=>[k,n[k]])));
context.queries=data.input.queries.map(q=>Object.fromEntries(['id','stratum','localTime','maxDistanceKm','remainingMinutes','maxTicketPrice','states'].map(k=>[k,q[k]])));
const contextJson=JSON.stringify(context),hash=s=>crypto.createHash('sha256').update(s).digest('hex');
data.resultExample={schemaVersion:1,artifactType:'OFFLINE_RESULT_VIEW',dataVerifiedByTool:false,realStudyComplete:false,contextJson,reportJson:files.report.toString('utf8'),hashes:{contextSha256:hash(contextJson),reportSha256:manifest.reportSha256,inputSha256:manifest.inputSha256},trace:{producer:'HISTORICAL_JAVA_EXPORT',algorithmVersion:data.report.version,buildId:null,sourceFileCount:Object.keys(manifest.sourceSha256).length}};
await validateResultView(JSON.stringify(data.resultExample));
const model=(await fs.readFile(path.join(root,'demo-model.mjs'),'utf8')).replaceAll('export function','function');
const resultModel=(await fs.readFile(path.join(root,'result-view-model.mjs'),'utf8')).replace(/^import .*\r?\n/gm,'').replace(/^export /gm,'');
const resultUi=await fs.readFile(path.join(root,'result-view-ui.js'),'utf8');
const rankingModel=(await fs.readFile(path.join(root,'ranking-evidence.mjs'),'utf8')).replace(/^export /gm,'');
const rankingUi=await fs.readFile(path.join(root,'ranking-evidence-ui.js'),'utf8');
const template=(await fs.readFile(path.join(root,'page.html'),'utf8')).replace('__RESULT_VIEW_MODEL__',()=>resultModel).replace('__RESULT_VIEW_UI__',()=>resultUi).replace('__RANKING_EVIDENCE_MODEL__',()=>rankingModel).replace('__RANKING_EVIDENCE_UI__',()=>rankingUi);
const ui=await fs.readFile(path.join(root,'robustness-ui.js'),'utf8');
const fieldworkModel=(await fs.readFile(path.join(root,'fieldwork-model.mjs'),'utf8')).replace(/^export /gm,'');
const fieldworkUi=await fs.readFile(path.join(root,'fieldwork-ui.js'),'utf8');
const labUi=await fs.readFile(path.join(root,'lab-ui.js'),'utf8');
const html=template.replace('__DATA__',()=>JSON.stringify(data).replaceAll('<','\\u003c')).replace('__MODEL__',()=>model).replace('__ROBUSTNESS_UI__',()=>ui).replace('__FIELDWORK_MODEL__',()=>fieldworkModel).replace('__FIELDWORK_UI__',()=>fieldworkUi).replace('__LAB_UI__',()=>labUi);
await fs.writeFile(path.join(root,'index.html'),html);
const webSourceSha256={};for(const name of ['page.html','demo-model.mjs','robustness-ui.js','fieldwork-model.mjs','fieldwork-ui.js','lab-ui.js','result-view-model.mjs','result-view-ui.js','ranking-evidence.mjs','ranking-evidence-ui.js'])webSourceSha256[name]=crypto.createHash('sha256').update(await fs.readFile(path.join(root,name))).digest('hex');
await fs.writeFile(path.join(root,'manifest.json'),JSON.stringify({createdOn:'2026-11-11',purpose:'报告回放、可核对的推荐依据与公平取舍、离线答辩、本地Java实验',...data.provenance,webSourceSha256,htmlSha256:crypto.createHash('sha256').update(html).digest('hex'),paidApiCalls:0,databaseWrites:0},null,2));
console.log('已生成可独立打开的 index.html，输入和报告校验和一致。');
