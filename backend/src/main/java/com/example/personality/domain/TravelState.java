package com.example.personality.domain;

import java.util.Map;

/**
 * 「此刻的状态」——用户主动告诉系统的当前处境，和长期偏好是两回事。
 *
 * <h2>为什么要和画像分开</h2>
 *
 * <p>计划书第七节的产品原则第二条：
 * <blockquote>长期偏好与当前状态必须分开。</blockquote>
 *
 * <p>因为它们的<b>生命周期完全不同</b>：
 * <ul>
 *   <li><b>长期偏好</b>（{@link TravelProfile}）——"你喜欢自然风光"，
 *       存进数据库，下次来还在</li>
 *   <li><b>当前状态</b>（这个枚举）——"你累了"，
 *       <b>只对接下来这一两个小时有意义</b>，不该持久化</li>
 * </ul>
 *
 * <p>如果把"我饿了"写进画像，就成了永久的偏好改变——用户第二天来，
 * 系统还以为他饿着。所以状态只存在于那一次推荐请求里。
 *
 * <h2>⚠️ 状态作用于「地点属性」，不是「用户偏好」</h2>
 *
 * <p>这里有个<b>踩过的坑</b>，值得记下来。
 *
 * <p>最初把"我累了"实现成"把用户的步行意愿从 100 降到 60"。结果测试直接红了：
 * 排序完全没变。原因是兴趣分是个<b>归一化的加权平均</b>——
 * 如果步行意愿是唯一有权重的维度，把它的权重调小，<b>排序一点都不会变</b>
 * （分子分母同时缩小，比值不变）。
 *
 * <p>更重要的是语义就错了：<b>"我累了"不是"我没那么在乎走路了"，
 * 而是"费腿的地方要变差"。</b>这是一件关于<b>地点</b>的事，不是关于<b>你</b>的事。
 *
 * <p>所以现在模型是：状态给某些属性加一个<b>偏向值</b>，直接乘在兴趣分上：
 * <pre>
 *   状态系数 = Π (1 + 偏向 × 该地点在这个维度上的得分/100) / (1 + max(偏向, 0))
 * </pre>
 *
 * <p>举例（偏向 = -0.8，"累了"）：
 * <ul>
 *   <li>费腿的地方（walking=95）→ 系数 0.24，几乎被压掉</li>
 *   <li>平缓的地方（walking=10）→ 系数 0.92，几乎不受影响</li>
 * </ul>
 *
 * <p>除以 {@code (1 + max(偏向, 0))} 是<b>必须的归一化</b>：不除的话，
 * 正偏向会让系数大于 1，进而让总分超过 1——而数据库上有
 * {@code CHECK (score BETWEEN 0 AND 1)} 卡着，存库直接失败。
 * 除了之后所有系数都 ≤ 1，和另外两个因子（距离、质量）一样。
 *
 * <h2>为什么把影响写在枚举上</h2>
 *
 * <p>"累了意味着什么"是<b>产品知识</b>，不是调用方该知道的事。
 * 如果让前端传"给 walking 乘 0.24"，等于把算法拆到了前端——
 * 改一次策略要同时改前后端，不同客户端的表现还会不一致。
 */
public enum TravelState {

    /**
     * 有点累了。
     *
     * <p>惩罚"费腿"这个属性：越费腿的地方折扣越大。
     *
     * <p>⚠️ 这里<b>只调了属性偏向</b>，没有同时收紧"能接受的停留时长"。
     * 那是个更严格的处理（累了应该连"要逛 3 小时的地方"也排除掉），
     * 但它需要引擎多一个概念。先做简单的，觉得不够再补。
     */
    TIRED("有点累了", Map.of(TravelDimension.WALKING, -0.8)),

    /** 想吃饭了。奖励"美食"属性——附近合适的馆子会一下子冒到前面。 */
    HUNGRY("想吃饭了", Map.of(TravelDimension.FOOD, 0.8)),

    /** 想散散步。和 {@link #TIRED} 正好相反，奖励"费腿"属性。 */
    WANT_WALK("想散散步", Map.of(TravelDimension.WALKING, 0.8)),

    // ==========================================================
    // 下面四个是接入「自然语言状态输入」时补的
    // ==========================================================
    // 用户会说的话远不止"累了/饿了/想散步"三类。补这几个是因为
    // 它们是日常表达里最常出现、而原有词表又表达不了的：
    //     "想找个安静的地方坐坐"、"想拍点照"、"想看点有文化的东西"、"想亲近自然"
    //
    // ⚠️ 加值时**必须检查它和已有状态在维度上有没有重叠**。
    //    重叠的维度会**相加**（见 TravelState 的类注释），而相加就可能越过 ±1——
    //    越过之后打分系数会变成负数，直接撞上数据库的
    //    CHECK (score BETWEEN 0 AND 1)，接口 500。
    //    （引擎现在会按维度求和后夹到 [-1, 1] 兜住这件事，
    //      但那是保险丝，不是"可以随便重叠"的许可。）
    //
    // 当前四个新值的维度都不与任何已有状态重叠。

    /**
     * 想安静点。
     *
     * <p>惩罚"热闹"属性——人多的地方排后面。
     * 和"想散步"不冲突：安静的小路是两者的交集，这正是对的。
     */
    QUIET("想安静点", Map.of(TravelDimension.CROWD_TOLERANCE, -0.8)),

    /** 想拍点照。奖励"出片"属性。 */
    PHOTO("想拍点照", Map.of(TravelDimension.PHOTOGRAPHY, 0.8)),

    /** 想看点人文的。奖励"文化"属性。 */
    CULTURE("想看点人文的", Map.of(TravelDimension.CULTURE, 0.8)),

    /** 想亲近自然。奖励"自然"属性。 */
    NATURE("想亲近自然", Map.of(TravelDimension.NATURE, 0.8));

    /**
     * 偏向值取 0.8 而不是更小：<b>状态是"此刻的强信号"。</b>
     *
     * <p>用户说"我饿了"，就是现在、马上要吃饭，不是"我最近对美食的偏好上升了"。
     * 0.8 足以让相关属性从"几乎压掉（0.24）"到"几乎顶满（0.98）"，
     * 结果明显改变——状态本来就是用来"立刻改变推荐"的。
     *
     * <p>（对比：反馈修正是 ±10 分、累计封顶 ±40，作用在偏好上、会持久留痕。
     * 两者量级和机制不同是刻意的：一个是长期累积的小修正，一个是此刻的强信号。）
     */
    private final String label;

    private final Map<TravelDimension, Double> attributeBias;

    TravelState(String label, Map<TravelDimension, Double> attributeBias) {
        this.label = label;
        this.attributeBias = attributeBias;
    }

    /** 中文展示名，用于 API 响应和前端按钮。 */
    public String label() {
        return label;
    }

    /**
     * 这个状态偏向哪些地点属性、偏多少。
     *
     * <p>取值 -1 ~ 1：正数表示"这个属性越高越好"，负数表示"越高越差"。
     * 返回的是不可变 Map，调用方改不了。
     */
    public Map<TravelDimension, Double> attributeBias() {
        return attributeBias;
    }
}
