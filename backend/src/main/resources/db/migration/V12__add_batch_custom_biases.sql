-- ============================================================
-- V12: 记住「自然语言解析出来的原始维度偏向」
-- ============================================================
-- 前置：V11（recommendation_batches）
--
-- 做的是哪件事：用户说「我累了想找个安静的地方坐坐」时，
-- "累了"和"想安静"都落在词表（travel_states）里有现成的名字，
-- 但用户还可能说出词表覆盖不了的话——比如"想找个能带猫的咖啡馆"。
-- 那种情况由 AI 解析成**原始的维度偏向**，存在这一列里。
--
-- 【为什么必须存】
--
-- 和 V11 存五因子是同一个理由：生成 AI 推荐理由时是**另一次请求**，
-- 那时内存里早就没东西了，只能从数据库重建"当初按什么算的"。
-- 不存的话，AI 写理由时会漏掉"用户特意说了想安静"这件事——
-- 而那恰恰是用户最在意的一句话。
--
-- 【⚠️ 为什么不和 states 合并成一列】
--
-- states 里存的是**枚举名**（TIRED、QUIET），它有人类可读的身份：
-- 界面上显示成"有点累了"，日志里一眼能看懂，加新状态也不用改表。
-- 原始偏向没有这层身份——它就是几个"维度 → 数值"。
--
-- 两种东西混进一列，展示和解析都会变得很难写（要先生成字符串再猜
-- 这一段是名字还是数值），所以宁可多一列。
--
-- 【为什么还是逗号串而不是 JSONB】
--
-- 和 states 那一列同样的取舍：取值最多七个（会影响地点选择的维度就 7 个）、
-- 写完只读不查、数组/JSON 类型在 JPA 侧要额外配置才映射得了。够用就好。
--
-- 格式：`维度名:偏向`，逗号分隔，偏向固定两位小数。
--     CROWD_TOLERANCE:-0.80,PHOTOGRAPHY:0.60
-- 固定小数位是为了同一份数据序列化稳定——不然字符串比较类的测试会飘。
-- ------------------------------------------------------------

ALTER TABLE recommendation_batches
    ADD COLUMN custom_biases VARCHAR(256) NOT NULL DEFAULT '';

COMMENT ON COLUMN recommendation_batches.custom_biases IS
    '自然语言解析出的原始维度偏向，格式 "CROWD_TOLERANCE:-0.80,PHOTOGRAPHY:0.60"；空串表示没有。'
    ' 词表（travel_states）覆盖不了的用户表达才会落到这里。';

-- ------------------------------------------------------------
-- 3. 自检：确认列加上了、且默认值确实生效
-- ------------------------------------------------------------
-- 这一步看着多余，但它拦的是一种很实际的错：迁移写了一半、
-- 或者 DEFAULT 忘了写导致历史行是 NULL——而代码那边读的是
-- "空串表示没有偏向"，读到 NULL 会在解析时抛空指针。
-- 迁移只跑一次，这里断言一次很便宜。
DO $$
DECLARE
    null_count INTEGER;
BEGIN
    SELECT COUNT(*) INTO null_count
    FROM recommendation_batches
    WHERE custom_biases IS NULL;

    IF null_count > 0 THEN
        RAISE EXCEPTION 'custom_biases 有 % 行是 NULL，代码期望的是空串', null_count;
    END IF;

    RAISE NOTICE 'custom_biases 列就绪，历史行已回填为空串';
END $$;
