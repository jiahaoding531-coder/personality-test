-- ============================================================
-- V7: 地点表 + 50 个模拟 POI
-- ============================================================
-- 对应 TravelMind 计划书第二十四节的第一步：
--     「用 Python 建立 20～50 个模拟旅游地点」
--
-- 【为什么先做模拟数据】
--
-- 计划书的原则是"先证明核心价值，再扩大技术复杂度"。
-- 真实的 POI 数据（高德/百度）要走申请、有配额限制、字段还不一定够用。
-- 而 V0 要验证的是**推荐算法本身准不准**——
-- 这件事用模拟数据就能验证，而且比真实数据更可控：
-- 每个地点的属性都是我们手工标注的，算法算错了能立刻定位。
--
-- 等推荐效果验证过了，再把 places 表的数据源换成真实 API 才有意义。
-- 反过来的话，你会同时面对"算法对不对"和"数据全不全"两个问题。
--
-- 【关于属性设计】
--
-- 7 个属性维度（0~100）严格对应 V6 里的旅行偏好维度：
--
--   用户偏好            ←→    地点属性
--   NATURE  自然              nature        这个地方有多自然
--   CULTURE 人文              culture       历史/文化浓度
--   FOOD    美食              food          餐饮属性强弱
--   PHOTOGRAPHY 摄影          photography   出片程度
--   HIDDEN_GEMS 小众          hidden_gems   冷门程度（越高越没人知道）
--   CROWD_TOLERANCE 人群容忍  lively        热闹程度（越高人越多）
--   WALKING 步行意愿          walking       步行强度（越高越费腿）
--
-- 推荐的核心就是：**把你想要的，和这个地方能给的，对上。**
-- ============================================================

CREATE TABLE places (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    category    VARCHAR(32)  NOT NULL,
    city        VARCHAR(50)  NOT NULL,

    -- 坐标。用 double precision 而不是 numeric：
    -- 经纬度是连续量，不需要精确小数运算，double 足够且更省空间。
    latitude    DOUBLE PRECISION NOT NULL,
    longitude   DOUBLE PRECISION NOT NULL,

    -- ---- 7 个属性维度，0~100 ----
    nature       INTEGER NOT NULL DEFAULT 0,
    culture      INTEGER NOT NULL DEFAULT 0,
    food         INTEGER NOT NULL DEFAULT 0,
    photography  INTEGER NOT NULL DEFAULT 0,
    hidden_gems  INTEGER NOT NULL DEFAULT 0,
    lively       INTEGER NOT NULL DEFAULT 0,
    walking      INTEGER NOT NULL DEFAULT 0,

    -- ---- 实用性字段 ----
    ticket_price      INT NOT NULL DEFAULT 0,      -- 门票（元），0 表示免费
    suggested_minutes INT NOT NULL DEFAULT 60,     -- 建议停留时长（分钟）

    -- 营业时间。用 TIME 而不是字符串，方便做"现在开没开门"的判断。
    -- NULL 表示全天开放（比如公园、街区）。
    open_from   TIME,
    open_to     TIME,

    quality     INTEGER NOT NULL DEFAULT 60,      -- 综合质量分 0~100
    description VARCHAR(300),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT ck_places_attrs CHECK (
        nature BETWEEN 0 AND 100 AND culture BETWEEN 0 AND 100 AND
        food BETWEEN 0 AND 100 AND photography BETWEEN 0 AND 100 AND
        hidden_gems BETWEEN 0 AND 100 AND lively BETWEEN 0 AND 100 AND
        walking BETWEEN 0 AND 100 AND quality BETWEEN 0 AND 100
    ),
    CONSTRAINT ck_places_category CHECK (category IN (
        'NATURE', 'CULTURE', 'FOOD', 'PHOTO', 'DISTRICT', 'MUSEUM', 'MARKET'
    ))
);

CREATE INDEX idx_places_city ON places (city);

COMMENT ON TABLE places IS
    '旅游地点。V0 用模拟数据验证推荐算法；将来可换成高德等真实 API 的数据源。';

