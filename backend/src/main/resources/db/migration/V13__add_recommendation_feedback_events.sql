-- ============================================================
-- V13: 保存自然语言推荐反馈事件
-- ============================================================
-- 这张表保存的是“用户当时说了什么，以及服务端最终接受了哪些结构化语义”。
-- 它是只追加的事实表；不会保存用户 key、Prompt 或模型原始响应。

CREATE TABLE recommendation_feedback_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES test_sessions(id) ON DELETE CASCADE,
    recommendation_id BIGINT REFERENCES recommendations(id) ON DELETE CASCADE,
    raw_text VARCHAR(200) NOT NULL,
    feedback_kind VARCHAR(32) NOT NULL,
    place_reaction VARCHAR(16),
    feedback_signals JSONB NOT NULL DEFAULT '[]'::jsonb,
    structured_operations JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT ck_feedback_event_kind CHECK (
        feedback_kind IN ('PLACE_OPINION', 'SESSION_ADJUSTMENT', 'MIXED')
    ),
    CONSTRAINT ck_feedback_event_reaction CHECK (
        place_reaction IS NULL OR place_reaction IN ('LIKE', 'DISLIKE')
    ),
    CONSTRAINT ck_feedback_event_signals_array CHECK (
        jsonb_typeof(feedback_signals) = 'array'
    ),
    CONSTRAINT ck_feedback_event_text CHECK (
        length(trim(raw_text)) BETWEEN 1 AND 200
    ),
    CONSTRAINT ck_feedback_event_operations_array CHECK (
        jsonb_typeof(structured_operations) = 'array'
    )
);

CREATE INDEX idx_feedback_events_session_created
    ON recommendation_feedback_events(session_id, created_at);

CREATE INDEX idx_feedback_events_recommendation
    ON recommendation_feedback_events(recommendation_id)
    WHERE recommendation_id IS NOT NULL;
