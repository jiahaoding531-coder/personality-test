-- ============================================================
-- V10: 地点增加「室内程度」，供天气参与打分
-- ============================================================
-- 前置：V7（places）
--
-- 做的是哪件事：让"下雨天别去户外景点"这条常识能真的算进推荐分。
--
-- 之前推荐引擎有四个因子（兴趣 × 距离 × 质量 × 状态），但**没有一个
-- 跟天气有关**——因为 places 表里根本没有描述"这个地方是不是在室内"
-- 的字段，算法无从下手。加天气之前必须先加这个。
--
-- ⚠️ 只新增这一个迁移文件，**绝不要回头改 V1~V9**。
--    Flyway 会校验已执行迁移的校验和，改动过的库启动时会直接失败。
--    要补东西就新开版本号。
-- ============================================================

-- ------------------------------------------------------------
-- 1. 新列：indoor
-- ------------------------------------------------------------
-- 【为什么是 0~100 的「室内程度」，而不是布尔值 is_indoor】
--
-- 两个理由，第二个更要命：
--
-- 1）表达力。真实的 POI 有大量"半室内"：河坊街是步行街但两侧店铺能进、
--    夜市有棚但主要在外面、天目里是商业综合体加户外广场。
--    布尔值逼着你二选一，而这个选择会直接影响下雨天推不推它。
--
-- 2）和这张表的其它属性保持一致。nature、culture、walking、quality
--    全都是 0~100 的强度值，没有一个是布尔。突然插一个布尔进来，
--    读代码的人得记住"这个字段不一样"——而这种例外每多一个，
--    这张表就越难理解。
--
-- 取值含义：
--     0 ~ 15   完全户外（公园、山、江边）
--    16 ~ 50   以户外为主，有少量可躲的地方
--    51 ~ 80   以室内为主，但要走一段
--    81 ~ 100  基本全程在室内（博物馆、商场）
--
-- 【为什么 DEFAULT 是 0】
--
-- 0 表示"完全户外"。漏标注时按户外处理，代价是这个地点下雨天被降权——
-- 属于**偏保守的错**：宁可让一个室内地点少被推荐几次，
-- 也不要让用户冒着雨跑到一个其实没顶的地方。
--
-- 反过来的默认值（100）会让所有没标注的地点下雨天照样排前面，
-- 那就等于这个功能没做。
-- ------------------------------------------------------------
-- ⚠️ 用 INTEGER 而不是 SMALLINT，虽然 0~100 塞得进 smallint。
--    V7 里那 7 个同类属性（nature/culture/.../quality）全是 INTEGER，
--    而 Java 侧全是 int。三处类型不一致的话，Hibernate 的
--    ddl-auto: validate 会在启动时直接拦下来：
--        wrong column type encountered in column [indoor];
--        found [int2 (Types#SMALLINT)], but expecting [integer (Types#INTEGER)]
--    省下的那 2 个字节（59 行 × 2B = 118 字节）不值这个麻烦。
ALTER TABLE places
    ADD COLUMN indoor INTEGER NOT NULL DEFAULT 0
        CONSTRAINT ck_places_indoor CHECK (indoor BETWEEN 0 AND 100);

COMMENT ON COLUMN places.indoor IS
    '室内程度 0~100。0=完全户外，100=全程室内。天气参与打分时用它决定"下雨天该不该降权"。';

