-- ------------------------------------------------------------
-- 3. 自检：确认标注真的生效了
-- ------------------------------------------------------------
-- ⚠️ 这一段不是多余的。上面按 name 匹配，而**匹配不上的时候不会报错**——
--    某个名字打错一个字，那一行就静默地保持 DEFAULT 0，
--    表现是这个地点下雨天被无端降权，而且没有任何迹象。
--
-- 断言"indoor 恰好等于 0 的有 12 条"。这个数字是有意义的：
-- 上面只有 12 个地点是**真的**完全户外（西湖·苏堤、九溪烟树、宝石山、
-- 太子湾、云栖竹径、湘湖、玉皇山、浴鹄湾、八卦田、断桥残雪、
-- 宝石山初阳台、钱塘江大桥）。
--
-- 多一条说明某个本该标非零的名字打错了（漏标）；
-- 少一条说明某个该是 0 的被标成了别的值。两种都是错，都要拦住。
--
-- 迁移脚本只会跑一次，所以这里"写死一个数字"是可以接受的——
-- 它换来的是"错的那一刻就炸"，而不是上线后才发现某几个地点永远被降权。
DO $$
DECLARE
    total   INTEGER;
    outdoor INTEGER;
    EXPECTED_TOTAL   CONSTANT INTEGER := 59;
    EXPECTED_OUTDOOR CONSTANT INTEGER := 12;
BEGIN
    SELECT COUNT(*) INTO total   FROM places;
    SELECT COUNT(*) INTO outdoor FROM places WHERE indoor = 0;

    RAISE NOTICE 'places 共 % 条，其中 indoor=0（完全户外）% 条', total, outdoor;

    IF total <> EXPECTED_TOTAL THEN
        RAISE EXCEPTION '预期 % 个地点，实际 %（V7 的种子数据变了吗？）',
            EXPECTED_TOTAL, total;
    END IF;

    IF outdoor <> EXPECTED_OUTDOOR THEN
        RAISE EXCEPTION '预期只有 % 个完全户外的地点，实际 %——很可能是上面的名字打错了，导致漏标',
            EXPECTED_OUTDOOR, outdoor;
    END IF;
END $$;
