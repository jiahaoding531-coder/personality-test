-- ============================================================
-- V6: 题库支持多套量表 + 旅行偏好题
-- ============================================================
-- 背景：项目原本只有一套人格量表（V2 灌入的 20 道题）。
-- 现在要加 TravelMind 的「旅行偏好测试」，需要让 questions 表
-- 支持多套量表并存，而不是另建一张表。
--
-- 【为什么复用 questions 表而不是新建一张】
--
-- 「出一组题 → 用户按 1~5 作答 → 算出若干维度的分数」这个流程
-- 两套量表完全一样。差异只在「维度叫什么名字」。
-- 复用意味着计分引擎（ScoringService）、作答流程、DTO 全都不用改，
-- 只是喂进去的数据不同。
--
-- 这也印证了当初把 ScoringService 的 itemCount 参数化的价值——
-- 人格题每维度 4 道，旅行题每维度 1 道，公式一行都不用动。
-- ============================================================

-- ------------------------------------------------------------
-- 1. 加 scale 列区分量表
-- ------------------------------------------------------------
ALTER TABLE questions ADD COLUMN scale VARCHAR(20) NOT NULL DEFAULT 'PERSONALITY';

COMMENT ON COLUMN questions.scale IS '所属量表：PERSONALITY=人格测试，TRAVEL=旅行偏好测试';

-- ------------------------------------------------------------
-- 2. 原来 dimension 上的 CHECK 约束要撤掉
-- ------------------------------------------------------------
-- V1 里写死了 dimension 只能是那 5 个人格维度：
--     CHECK (dimension IN ('OPENNESS', 'EXTRAVERSION', ...))
-- 旅行维度（NATURE、FOOD...）会被它挡住。
--
-- 撤掉之后，dimension 的合法性由**应用层的枚举**保证
-- （PersonalityDimension / TravelDimension）。
-- 这是个权衡：数据库少了一道防线，但换来扩展性。
-- 真要在库里做约束，可以改成按 scale 分别校验的复合 CHECK，
-- 但那样每加一个维度都要改表结构，得不偿失。
ALTER TABLE questions DROP CONSTRAINT ck_questions_dimension;

-- 新增 scale 的取值约束（这个约束很稳定，不会频繁变）
ALTER TABLE questions ADD CONSTRAINT ck_questions_scale
    CHECK (scale IN ('PERSONALITY', 'TRAVEL'));

-- ------------------------------------------------------------
-- 3. sort_order 的唯一约束要改成「量表内唯一」
-- ------------------------------------------------------------
-- 原来是全局唯一（uq_questions_sort_order），旅行题的 1~8
-- 会和人形题的 1~20 冲突。
ALTER TABLE questions DROP CONSTRAINT uq_questions_sort_order;
ALTER TABLE questions ADD CONSTRAINT uq_questions_scale_sort UNIQUE (scale, sort_order);

-- 按量表查题是最高频的查询（取人格题 / 取旅行题各一次）
CREATE INDEX idx_questions_scale ON questions (scale);

-- ============================================================
-- 4. 旅行偏好题（8 道，每个维度 1 道）
-- ============================================================
--
-- 【为什么只出 8 道、每维度 1 道】
--
-- 计划书第六节写的是「8～10 道场景题」，这里取下界。
-- 更重要的理由是计划书第七条的产品原则：
--
--     「测试只是初始猜测，真实行为和反馈更重要。」
--
-- 旅行偏好和人格不一样——它随目的地、季节、同行人变化，
-- 精确测出来意义不大。8 道题拿到一个粗略的初始方向就够，
-- 后面靠用户对推荐的反馈（喜欢/不喜欢）来修正。
--
-- 代价是每个维度只有 5 个可能取值（0/25/50/75/100），
-- 粒度很粗。但这是**刻意接受的**：粗但可靠的先验，
-- 好过精但过时的问卷结果。
--
-- 【为什么全部正向计分，没有反向题】
--
-- 人格测试里反向题是为了对付「默认同意」的作答倾向。
-- 但旅行偏好题写反向会变得很别扭：
--   「我不喜欢去人多的地方」的镜像是什么？「我喜欢去人多的地方」？
-- 两道题其实在测同一件事，只是绕了个弯，用户反而容易答错。
--
-- 直接问正向、语义清晰，对 8 道题的短问卷更合适。
-- ============================================================

