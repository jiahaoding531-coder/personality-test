-- ============================================================
-- V3: 给 ai_reports 加 provider 列
-- ============================================================
-- 记录这份报告是由哪个模型生成的，例如 "deepseek:deepseek-chat"。
--
-- 【为什么需要它】
--   1. 排查问题：用户反馈"这次生成的内容很奇怪"时，能立刻知道是哪个模型产出的
--   2. 将来对比：同时接多家模型（DeepSeek / 通义 / 智谱）做效果对比时，
--      需要区分数据来源
--   3. 输出稳定性：模型升级后输出风格会变，有这列才能回溯"升级前后"的差异
--
-- 【为什么是新增脚本而不是改 V1】
--   Flyway 会为每个已执行的脚本记录校验和。如果去改 V1，
--   所有已经跑过 V1 的环境（包括你本机、别人的机器、将来的服务器）
--   在下次启动时都会报 "Migration checksum mismatch"，
--   然后整个应用起不来。
--
--   正确的演进方式永远是：加一个新的、版本号更大的脚本。
--   表结构的历史因此也是可追溯的——你能看到它每一步是怎么长成现在这样的。
--
-- 【为什么允许 NULL】
--   V1 到 V3 之间可能已经有历史数据（比如手动插入的测试数据）。
--   加 NOT NULL 约束会要求提供默认值，而那些历史数据并没有真正对应的 provider。
--   留 NULL 表示"未知来源"，语义准确。
-- ============================================================

ALTER TABLE ai_reports ADD COLUMN provider VARCHAR(64);

COMMENT ON COLUMN ai_reports.provider IS '生成该报告的模型标识，如 deepseek:deepseek-chat；NULL 表示接入 AI 之前的数据';
