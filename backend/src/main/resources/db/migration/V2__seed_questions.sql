-- 【为什么 sort_order 要交错排列】
--   同一维度的题如果连续出现，用户会产生作答定势（发现"这几题是一伙的"
--   之后就会倾向于给一致答案），测出来的分数会失真。
--   这里的排列让每个维度的题均匀分布在 1/6/11/16、2/7/12/17 ... 等位置。
--
-- 【反向题是怎么判定的】
--   题干问的方向和维度本身相反，同意它就等于该维度得分低。
--   例：sort_order=11「比起探索新地方，我更愿意反复去熟悉的地方」
--       同意它 = 开放性低，所以必须反转成 6 - score。
--   每一道反向题的理由都写在下面的注释里。
--
-- 【量表】1=非常不同意  2=比较不同意  3=说不好  4=比较同意  5=非常同意
